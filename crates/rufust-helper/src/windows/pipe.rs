//! The elevated side of the desktop's private pipes.
//!
//! The unelevated window creates `\\.\pipe\<name>-control` (it writes) and
//! `\\.\pipe\<name>-events` (it reads), then starts this process through UAC
//! with `<name>`. One NDJSON request arrives on the control pipe; afterwards
//! a `cancel` line or the window closing the pipe requests cancellation.
//! Events, including the terminal result, go back on the events pipe.

use std::fs::{File, OpenOptions};
use std::io::{BufRead, BufReader, Read};
use std::sync::{Arc, Mutex};

use rufust_core::progress::CancellationToken;
use rufust_helper_protocol::{
    decode_line, HelperEvent, HelperRequest, HelperResult, MAX_MESSAGE_BYTES,
};

use crate::{write_event_line, ExecutionOptions, HelperError};

/// Pipe names are generated by the desktop; accept nothing that could
/// reach another path.
fn valid_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 64
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-')
}

/// Serve one request from the desktop. Returns the process exit code.
pub fn serve_pipe(name: &str) -> u8 {
    if !valid_name(name) {
        return 2;
    }
    let Ok(control) = File::open(format!(r"\\.\pipe\{name}-control")) else {
        return 2;
    };
    let Ok(events) = OpenOptions::new()
        .write(true)
        .open(format!(r"\\.\pipe\{name}-events"))
    else {
        return 2;
    };
    let events = Arc::new(Mutex::new(events));
    let mut control = BufReader::new(control);
    let mut line = Vec::new();
    let read = (&mut control)
        .take((MAX_MESSAGE_BYTES + 1) as u64)
        .read_until(b'\n', &mut line);
    if read.is_err() || line.len() > MAX_MESSAGE_BYTES {
        return 2;
    }
    let Ok(request) = decode_line::<HelperRequest>(&line) else {
        return 2;
    };
    let job_id = request.job_id;

    let cancel = CancellationToken::new();
    let watcher = cancel.clone();
    std::thread::spawn(move || {
        let mut command = String::new();
        loop {
            command.clear();
            match control.read_line(&mut command) {
                Ok(0) | Err(_) => break,
                Ok(_) if command.trim() == "cancel" => break,
                Ok(_) => {}
            }
        }
        watcher.request();
    });

    let sink_events = Arc::clone(&events);
    let result = crate::execute(
        request,
        ExecutionOptions {
            dry_run: false,
            cancel,
        },
        Box::new(move |event| {
            if let Ok(mut out) = sink_events.lock() {
                let _ = write_event_line(&mut *out, &event);
            }
        }),
    );
    match result {
        Ok(_) => 0,
        Err(error) => {
            let result = match error {
                HelperError::Cancelled => HelperResult::Cancelled {
                    message: "Operation cancelled; target media may be incomplete.".into(),
                },
                other => HelperResult::Failed {
                    code: "helper-operation".into(),
                    message: other.to_string(),
                },
            };
            if let Ok(mut out) = events.lock() {
                let _ = write_event_line(&mut *out, &HelperEvent::Finished { job_id, result });
            }
            1
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pipe_names_cannot_escape_the_pipe_namespace() {
        assert!(valid_name("rufust-1234-5678"));
        assert!(!valid_name(""));
        assert!(!valid_name(r"..\..\evil"));
        assert!(!valid_name("a/b"));
        assert!(!valid_name(&"a".repeat(65)));
    }
}
